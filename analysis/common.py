def paths():
    return {"v2": Path(os.environ.get("FET_V2", REPO / "frozen_release_v2")),
            "v1": Path(os.environ.get("FET_V1", REPO / "results")),
            "splits": Path(os.environ.get("FET_SPLITS", REPO / "splits")),
            "out": Path(os.environ.get("FET_OUT", REPO / "outputs"))}

def cli(description):
    """Parse --v2/--v1/--splits/--out and export them so every loader sees them."""
    ap = argparse.ArgumentParser(description=description)
    for k in ["v2", "v1", "splits", "out"]:
        ap.add_argument(f"--{k}", type=Path, default=None)
    a = ap.parse_args()
    for k in ["v2", "v1", "splits", "out"]:
        if getattr(a, k) is not None:
            os.environ[f"FET_{k.upper()}"] = str(getattr(a, k))
    return a

# ------------------------------------------------------------------ loaders
def pred(scale, cfg):
    return pd.read_csv(paths()["v2"] / "predictions" / f"{scale}_{cfg}_test_predictions.csv")

def v2_result(name):
    return pd.read_csv(paths()["v2"] / "results" / name)

def v1_result(name):
    return pd.read_csv(paths()["v1"] / name)

def e2_ci(scale, model, metric):
    e = v2_result("E2_bootstrap_ci_all.csv")
    return e[(e.scale == scale) & (e.model == model) & (e.metric == metric)].iloc[0]

# ------------------------------------------------------------------ metrics
def wr_at_k(y, score, k):
    """Share of positives in the top floor(k% * N) messages ranked by score (recall at budget)."""
    n = int(len(y) * k / 100); o = np.argsort(-score, kind="stable"); return y[o][:n].sum() / y.sum()

def budget_curve(y, score, grid):
    o = np.argsort(-score, kind="stable"); c = np.concatenate([[0], np.cumsum(y[o])]) / y.sum(); n = len(y)
    return np.array([c[int(n * k / 100)] for k in grid])

def effort_for_recall(y, score, target):
    o = np.argsort(-score, kind="stable"); c = np.cumsum(y[o]) / y.sum(); return (np.argmax(c >= target) + 1) / len(y)

def bootstrap_indices(n, b=N_BOOT, seed=SEED):
    rng = np.random.default_rng(seed); return [rng.integers(0, n, n) for _ in range(b)]

def text_models_100k():
    """y and scores of the two 100k text models, aligned on the same message order."""
    tf, db = pred(S100, "tfidf_text"), pred(S100, "distilbert_text")
    db = tf[["id"]].merge(db, on="id"); y = tf.y_true.values
    assert (db.y_true.values == y).all()
    return y, {"tfidf": tf.score.values, "distil": db.score.values}

