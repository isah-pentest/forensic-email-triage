"""Shared paths, loaders, metrics and plotting style for the figure/table scripts.

Where the saved results are read from (defaults: the copies in this repository):
  FET_V2      frozen_release_v2 folder (predictions/ and results/)
  FET_V1      v1 results folder (superseded late-fusion predictions, TREC07)
  FET_SPLITS  splits folder (split_meta.yaml)
  FET_OUT     output folder for figures (.pdf/.png) and tables (.csv, _rows.tex)
Set them with os.environ[...] in a notebook, or pass --v2/--v1/--splits/--out on the command line.
"""
